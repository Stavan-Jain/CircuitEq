_w8 = np.exp(1j * np.pi / 4)
MATS = {
    "H": np.array([[1, 1], [1, -1]], dtype=complex) / np.sqrt(2),
    "X": np.array([[0, 1], [1, 0]], dtype=complex),
    "Y": np.array([[0, -1j], [1j, 0]], dtype=complex),
    "Z": np.diag([1, -1]).astype(complex),
    "S": np.diag([1, 1j]).astype(complex),
    "Sdg": np.diag([1, -1j]).astype(complex),
    "T": np.diag([1, _w8]).astype(complex),
    "Tdg": np.diag([1, np.conj(_w8)]).astype(complex),
}


def _apply(state: np.ndarray, gate: Gate) -> np.ndarray:
    name, w = gate
    if name == "CX":
        c, t = w
        s = np.moveaxis(state, (c, t), (0, 1)).copy()
        s[1] = s[1][::-1].copy()
        return np.moveaxis(s, (0, 1), (c, t))
    s = np.moveaxis(state, w[0], 0)
    s = np.tensordot(MATS[name], s, axes=([1], [0]))
    return np.moveaxis(s, 0, w[0])


def unitary(gates: list[Gate], n: int) -> np.ndarray:
    u = np.eye(2 ** n, dtype=complex).reshape([2] * n + [2 ** n])
    for g in gates:
        u = _apply(u, g)
    return u.reshape(2 ** n, 2 ** n)


def compare(u: np.ndarray, v: np.ndarray) -> tuple[str, float | None]:
    """'exact', 'phase' (with the phase in units of pi) or 'different'."""
    if np.allclose(u, v, atol=1e-8):
        return "exact", None
    k = np.unravel_index(np.argmax(np.abs(u)), u.shape)
    ratio = v[k] / u[k]
    if abs(abs(ratio) - 1) < 1e-8 and np.allclose(u * ratio, v, atol=1e-8):
        return "phase", float(np.angle(ratio) / np.pi)
    return "different", None


def window_wires(left: list[Gate], right: list[Gate]) -> list[int]:
    """Wires in order of first appearance, as ``windowProof`` collects them."""
    wires: list[int] = []
    for _, w in left + right:
        for i in w:
            if i not in wires:
                wires.append(i)
    return wires


def window_valid(left: list[Gate], right: list[Gate]) -> bool:
    wires = window_wires(left, right)
    idx = {w: k for k, w in enumerate(wires)}
    ren = lambda gs: [(nm, tuple(idx[i] for i in w)) for nm, w in gs]  # noqa: E731
    k = len(wires)
    if k == 0:
        return True
    return compare(unitary(ren(left), k), unitary(ren(right), k))[0] == "exact"


