def survey_pair(name: str, pipeline: str, workdir: Path, timeout: float, no_lean: bool,
                lean_max_wires: int) -> dict:
    d = SURVEY / name
    original = zx.Circuit.load(str(d / "original.qasm"))
    optimized = cpb.optimize(original, pipeline)
    out = d / f"pyzx_{pipeline}.qasm"
    qasm = optimized.to_qasm()
    if out.exists() and out.read_text() != qasm:
        print(f"{name}/{pipeline}: PyZX output differs from the saved fixture; overwriting",
              file=sys.stderr)
    out.write_text(qasm)
    n = original.qubits
    rec = {"name": name, "pipeline": pipeline, "qubits": n,
           "pyzx_gates": [len(original.gates), len(optimized.gates)],
           "tcount": [original.tcount(), optimized.tcount()]}
    try:
        xs = parse(cpb.lean_instructions(original))
        ys = parse(cpb.lean_instructions(optimized))
    except ValueError as e:
        rec.update(aligned="no", reason=f"untranslatable PyZX output: {e}")
        return rec
    rec["lean_gates"] = [len(xs), len(ys)]
    kind, phase = compare(unitary(xs, n), unitary(ys, n)) if n <= 12 else ("unchecked", None)
    rec["numeric"] = kind if phase is None else f"phase {phase:.3f}*pi"
    rec["initial_windows"] = {c: initial_alignment(xs, ys, c).stats() for c in CANONS}
    found, rec["attempts"], rec["canon"] = best_alignment(xs, ys)
    if found is None:
        rec["aligned"] = "no"
        last = rec["attempts"][0]
        rec["reason"] = f"no alignment ({last['canon']}): {last['reason']}"
        rec["windows"] = last["last"]["windows"]
        rec["max_wires"] = last["last"]["max_wires"]
        rec["max_gates"] = last["last"]["max_gates"]
        if kind == "phase":
            rec["reason"] = f"equivalent only up to a global phase ({rec['numeric']}); " + rec["reason"]
        return rec
    st = found.stats()
    rec.update(windows=st["windows"], max_wires=st["max_wires"], max_gates=st["max_gates"],
               window_list=found.describe(), refinements=found.log)
    rec["whole_register"] = st["max_wires"] == n
    if rec["whole_register"]:
        rec["reason"] = (f"the only window found spans the whole register ({n} wires, "
                         f"{st['max_gates']} gates): a brute-force decide, not a window proof")
    if no_lean:
        rec["aligned"] = "model"
        return rec
    if st["max_wires"] > lean_max_wires:
        rec["aligned"] = "unchecked"
        rec["reason"] = (f"alignment found but its widest window has {st['max_wires']} wires "
                         f"({st['max_gates']} gates); not sent to Lean (bound {lean_max_wires} "
                         "wires, decide cost 2^k); " + rec.get("reason", ""))
        return rec
    ns = "Quantum.Circuit.Survey." + "".join(p.capitalize() for p in f"{name}_{pipeline}".split("_"))
    path = workdir / f"{name}_{pipeline}.lean"
    path.write_text(lean_module(ns, n, xs, ys, found))
    res = run_lean(path, timeout)
    rec["lean_time"] = res["time"]
    rec["lean_file"] = str(path)
    if res["ok"]:
        rec["aligned"] = "yes"
    elif res["timeout"]:
        rec["aligned"] = "timeout"
        rec["reason"] = f"Lean check exceeded {timeout:.0f} s (widest window {st['max_wires']} wires)"
    else:
        rec["aligned"] = "no"
        first = res["errors"][0] if res["errors"] else res["output"][-500:]
        rec["reason"] = f"Lean rejected the alignment ({classify_lean_error(first)}): {first[:300]}"
        rec["lean_output"] = res["output"]
    return rec


def markdown_table(records: list[dict]) -> str:
    rows = ["| Circuit | Pipeline | Qubits | Gates | T-count | Matched | Aligned | Windows | "
            "Widest window | Lean time | Notes |",
            "|---|---|---:|---:|---:|---:|---|---:|---|---:|---|"]
    for r in records:
        g = r.get("lean_gates", r["pyzx_gates"])
        widest = f"{r['max_wires']}w / {r['max_gates']}g" if r.get("windows") else "—"
        t = f"{r['lean_time']:.0f} s" if "lean_time" in r else "—"
        matched = "—"
        if r.get("attempts"):
            a = r["attempts"][0]
            matched = f"{a['matched']}/{g[0]}"
        aligned = r.get("aligned", "?")
        if r.get("whole_register"):
            aligned += " (whole register)"
        rows.append(f"| {r['name']} | {r['pipeline']} | {r['qubits']} | {g[0]} → {g[1]} | "
                    f"{r['tcount'][0]} → {r['tcount'][1]} | {matched} | {aligned} | "
                    f"{r.get('windows', 0)} | {widest} | {t} | {r.get('note', '')} |")
    return "\n".join(rows)


def self_test() -> None:
    """Sanity checks of the generators and the replay model."""
    if zx.__version__ != "0.9.0":
        raise RuntimeError(f"Expected PyZX 0.9.0, found {zx.__version__}")
    toffoli = np.eye(8, dtype=complex)
    toffoli[[6, 7]] = toffoli[[7, 6]]
    u = unitary(ccx(0, 1, 2), 3)
    # axis order: qubit 0 is the most significant bit of the row index
    assert compare(u, toffoli)[0] == "exact", "ccx is not a Toffoli"
    ccz_mat = np.diag([1, 1, 1, 1, 1, 1, 1, -1]).astype(complex)
    assert compare(unitary(ccz(0, 1, 2), 3), ccz_mat)[0] == "exact", "ccz is not a CCZ"
    q, g = cuccaro(2)
    u = unitary(g, q)
    for x in range(2 ** q):
        bits = [(x >> (q - 1 - i)) & 1 for i in range(q)]
        c, b0, a0, b1, a1, z = bits
        a, b = a0 + 2 * a1, b0 + 2 * b1
        s = a + b + c
        s0, s1, carry = s & 1, (s >> 1) & 1, (s >> 2) & 1
        want = [c, s0, a0, s1, a1, z ^ carry]
        y = sum(bit << (q - 1 - i) for i, bit in enumerate(want))
        assert abs(u[y, x] - 1) < 1e-9, "cuccaro(2) is not an adder"
    src = ROOT / "benchmarks" / "tof_3"
    xs = parse(cpb.lean_instructions(zx.Circuit.load(str(src / "original.qasm"))))
    ys = parse(cpb.lean_instructions(zx.Circuit.load(str(src / "pyzx.qasm"))))
    assert tof(3)[1] == xs
    hand = [([one("T", 0), one("T", 0)], [one("S", 0)]),
            ([one("H", 3), cx(1, 3)], [one("H", 3), cx(1, 3), one("H", 3), one("H", 3)]),
            ([one("H", 4), cx(2, 4)], [one("H", 4), cx(2, 4), one("H", 4), one("H", 4)]),
            ([one("Tdg", 2), cx(3, 2), one("H", 3), cx(1, 3)],
             [one("H", 3), cx(1, 3), one("H", 3), one("Tdg", 2), cx(3, 2), one("H", 3)])]
    al = Alignment(xs, ys, [], {}, "hand")
    al.lists = lambda w: hand[w]  # type: ignore[method-assign]
    al.windows = [([], [])] * 4
    r = replay(al, dynamic=False)
    assert r.ok and r.fired == [0, 1, 2, 3], "the Tof3 alignment does not replay"
    print("self-test passed")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--generate", action="store_true", help="write the original circuits")
    parser.add_argument("--force", action="store_true", help="overwrite existing originals")
    parser.add_argument("--self-test", action="store_true")
    parser.add_argument("--table", action="store_true", help="print results.json as Markdown")
    parser.add_argument("--circuits", nargs="*", help="subset of circuit names")
    parser.add_argument("--pipelines", nargs="*", default=list(PIPELINES), choices=PIPELINES)
    parser.add_argument("--timeout", type=float, default=600, help="Lean seconds per pair")
    parser.add_argument("--lean-max-wires", type=int, default=LEAN_MAX_WIRES)
    parser.add_argument("--no-lean", action="store_true", help="model only, no Lean runs")
    parser.add_argument("--workdir", type=Path, default=Path(os.environ.get(
        "TCOUNT_SURVEY_WORKDIR", "/tmp/tcount_survey")))
    parser.add_argument("--results", type=Path, default=SURVEY / "results.json")
    parser.add_argument("--emit", nargs=2, metavar=("NAME", "PIPELINE"),
                        help="print the Lean module of one aligned pair")
    args = parser.parse_args()
    if zx.__version__ != "0.9.0":
        raise RuntimeError(f"Expected PyZX 0.9.0, found {zx.__version__}")
    if args.self_test:
        self_test()
        return
    if args.generate:
        generate(args.force)
        return
    if args.table:
        print(markdown_table(json.loads(args.results.read_text())))
        return
    args.workdir.mkdir(parents=True, exist_ok=True)
    names = args.circuits or sorted(p.name for p in SURVEY.iterdir()
                                    if (p / "original.qasm").exists())
    if args.emit:
        name, pipeline = args.emit
        original = zx.Circuit.load(str(SURVEY / name / "original.qasm"))
        xs = parse(cpb.lean_instructions(original))
        ys = parse(cpb.lean_instructions(cpb.optimize(original, pipeline)))
        found, _, _ = best_alignment(xs, ys)
        if found is None:
            raise SystemExit("no alignment found")
        print(lean_module("Quantum.Circuit.Benchmarks.X", original.qubits, xs, ys, found))
        return
    records = []
    if args.results.exists():
        records = [r for r in json.loads(args.results.read_text())
                   if not (r["name"] in names and r["pipeline"] in args.pipelines)]
    for name in names:
        for pipeline in args.pipelines:
            t0 = time.time()
            rec = survey_pair(name, pipeline, args.workdir, args.timeout, args.no_lean,
                              args.lean_max_wires)
            rec["wall_time"] = round(time.time() - t0, 1)
            records.append(rec)
            print(f"{name}/{pipeline}: {rec.get('aligned')} windows={rec.get('windows')} "
                  f"widest={rec.get('max_wires')}w/{rec.get('max_gates')}g "
                  f"lean={rec.get('lean_time', '-')}s {rec.get('reason', '')}", flush=True)
            records.sort(key=lambda r: (names.index(r["name"]) if r["name"] in names else -1,
                                        PIPELINES.index(r["pipeline"])))
            args.results.write_text(json.dumps(records, indent=1, default=str) + "\n")


if __name__ == "__main__":
    main()
