Item = tuple[int, Gate]  # (raw index, gate)


def pull_one(g: Gate, xs: list[Item]):
    """First occurrence of ``g`` that commutes with everything before it.

    Returns ``(rest, index, None)`` or ``(None, None, (kind, blockers))`` with
    ``kind`` ``"blocked"`` (blockers of the first occurrence) or ``"absent"``.
    """
    first_blockers = None
    for k, (i, h) in enumerate(xs):
        if h == g:
            blockers = [xs[m] for m in range(k) if not can_commute(g, xs[m][1])]
            if not blockers:
                return xs[:k] + xs[k + 1:], i, None
            if first_blockers is None:
                first_blockers = blockers
    if first_blockers is None:
        return None, None, ("absent", [])
    return None, None, ("blocked", first_blockers)


def pull_many(gates: list[Gate], xs: list[Item]):
    """Pull ``gates`` in order; returns ``(rest, consumed, None)`` or
    ``(None, None, (position, gate, kind, blockers))``."""
    consumed = []
    for pos, g in enumerate(gates):
        xs, i, err = pull_one(g, xs)
        if err:
            return None, None, (pos, g, *err)
        consumed.append(i)
    return xs, consumed, None


@dataclass
class Replay:
    ok: bool
    fired: list[int]
    consumed_x: set[int]
    consumed_y: set[int]
    failure: dict | None = None


def replay(al: Alignment, dynamic: bool = True) -> Replay:
    """``alignWindows`` of ``CircuitEq/Tactic.lean``: at each step fire the
    pending window if both sides can be pulled to the front, else pull the next
    gate of ``ys`` from ``xs``. With ``dynamic`` every pending window is tried,
    which yields the order in which the tactic must be given them."""
    xs: list[Item] = list(enumerate(al.xs))
    ys: list[Item] = list(enumerate(al.ys))
    pending = list(range(len(al.windows)))
    fired: list[int] = []
    cons_x: set[int] = set()
    cons_y: set[int] = set()

    def fail(kind, **info):
        return Replay(False, fired, cons_x, cons_y,
                      {"kind": kind, "pending": list(pending), "xs": xs, "ys": ys, **info})

    while True:
        done = False
        for w in (pending if dynamic else pending[:1]):
            left, right = al.lists(w)
            xs2, cx2, err = pull_many(left, xs)
            if err:
                continue
            ys2, cy2, err = pull_many(right, ys)
            if err:
                continue
            xs, ys = xs2, ys2
            cons_x.update(cx2)
            cons_y.update(cy2)
            fired.append(w)
            pending.remove(w)
            done = True
            break
        if done:
            continue
        if not ys:
            if pending:
                return fail("not_placed", window=pending[0])
            if xs:
                return fail("unmatched_left", left=[i for i, _ in xs])
            return Replay(True, fired, cons_x, cons_y)
        (j, y) = ys[0]
        xs2, i, err = pull_one(y, xs)
        if err:
            return fail(err[0], y=(j, y), blockers=err[1])
        ys = ys[1:]
        xs = xs2
        cons_x.add(i)
        cons_y.add(j)


def diagnose_window(al: Alignment, w: int, xs: list[Item], ys: list[Item]) -> dict:
    """Why window ``w`` cannot fire on the remaining lists."""
    left, right = al.lists(w)
    _, _, err = pull_many(left, xs)
    if err:
        pos, g, kind, blockers = err
        return {"side": "left", "gate": g, "kind": kind, "blockers": blockers}
    _, _, err = pull_many(right, ys)
    if err:
        pos, g, kind, blockers = err
        return {"side": "right", "gate": g, "kind": kind, "blockers": blockers}
    return {"side": None, "kind": "pullable"}


