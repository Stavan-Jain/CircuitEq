class GiveUp(Exception):
    pass


def _absorb_blockers(al: Alignment, w: int, side: str, blockers: list[Item],
                     consumed_x: set[int], consumed_y: set[int]) -> int:
    """Absorb the blocking gates (with their matches) into window ``w``,
    merging windows that own a blocker; returns the resulting window id."""
    inv = al.inverse()
    ws = [w]
    pairs = []
    for idx, _ in blockers:
        owner = al.owner_x(idx) if side == "left" else al.owner_y(idx)
        if owner is not None:
            ws.append(owner)
        elif side == "left":
            j = al.match.get(idx)
            if j is None or j in consumed_y:
                raise GiveUp("occurrence ambiguity: a blocking context gate's partner was "
                             "already consumed by an earlier pull of an equal gate")
            pairs.append((idx, j))
        else:
            i = inv.get(idx)
            if i is None or i in consumed_x:
                raise GiveUp("occurrence ambiguity: a blocking context gate's partner was "
                             "already consumed by an earlier pull of an equal gate")
            pairs.append((i, idx))
    w = al.merge(ws) if len(ws) > 1 else w
    for i, j in pairs:
        al.absorb(w, i, j)
    return w


def refine(al: Alignment, r: Replay) -> Alignment:
    """One refinement step from a replay failure; raises ``GiveUp``."""
    f = r.failure
    al = al.copy()
    inv = al.inverse()
    if f["kind"] in ("blocked", "absent"):
        j, y = f["y"]
        w = al.owner_y(j)
        if w is None:  # a context gate
            i = inv.get(j)
            if f["kind"] == "absent" or i is None:
                raise GiveUp(f"context gate {show(y)} has no pullable partner left: an earlier "
                             "pull consumed an equal gate (occurrence ambiguity)")
            owners = {al.owner_x(b) for b, _ in f["blockers"]} - {None}
            if owners:
                w = al.merge(sorted(owners))
                al.absorb(w, i, j)
                al.log.append(f"absorb {show(y)} into the window whose gates block it")
            else:
                w = al.new_window(i, j)
                al.log.append(f"new commutation window at {show(y)}")
            w = _absorb_blockers(al, w, "left", [b for b in f["blockers"]
                                                 if al.owner_x(b[0]) is None and b[0] != i],
                                 r.consumed_x, r.consumed_y)
        else:
            d = diagnose_window(al, w, f["xs"], f["ys"])
            if d["kind"] == "absent":
                raise GiveUp(f"window gate {show(d['gate'])} was consumed as context earlier "
                             "(occurrence ambiguity)")
            if d["kind"] == "pullable":
                raise GiveUp("window reported unplaceable but pullable (model inconsistency)")
            al.log.append(f"grow window by the gates blocking {show(d['gate'])} on its {d['side']}")
            _absorb_blockers(al, w, d["side"], d["blockers"], r.consumed_x, r.consumed_y)
    elif f["kind"] == "not_placed":
        w = f["window"]
        d = diagnose_window(al, w, f["xs"], f["ys"])
        if d["kind"] != "blocked":
            raise GiveUp(f"window could not be placed at the end ({d['kind']})")
        al.log.append(f"grow window by the gates blocking {show(d['gate'])} on its {d['side']}")
        _absorb_blockers(al, w, d["side"], d["blockers"], r.consumed_x, r.consumed_y)
    else:
        raise GiveUp("unmatched instructions on the left after the walk")
    return al


def _time(al: Alignment, w: int) -> int:
    """A raw-``xs`` coordinate for a window, for nearest-neighbour merging."""
    a, b = al.windows[w]
    if a:
        return min(a)
    inv = al.inverse()
    before = [inv[j] for j in range(min(b)) if j in inv]
    return max(before, default=-1) + 1


def rematch(al: Alignment) -> Alignment:
    """Pair identical gates of a pure deletion with a pure insertion as context.

    A single non-local move perturbs the canonical interleaving of nearby
    independent gates, and the diff then reports them deleted here and
    inserted there. Those are moves, not rewrites; the replay handles the
    licensed ones and the blocked ones become commutation windows."""
    al = al.copy()
    while True:
        best = None
        for u, (a, b) in enumerate(al.windows):
            if not a or b:
                continue
            for v, (a2, b2) in enumerate(al.windows):
                if a2 or not b2:
                    continue
                used, pairs = set(), []
                for i in a:
                    for j in b2:
                        if j not in used and al.xs[i] == al.ys[j]:
                            used.add(j)
                            pairs.append((i, j))
                            break
                if pairs and (best is None or len(pairs) > len(best[2])):
                    best = (u, v, pairs)
        if best is None:
            return al
        u, v, pairs = best
        for i, j in pairs:
            al.windows[u][0].remove(i)
            al.windows[v][1].remove(j)
            al.match[i] = j
        al.log.append(f"re-match {len(pairs)} moved gates ({show(al.xs[pairs[0][0]])}, …) as context")
        al.windows = [(a, b) for a, b in al.windows if a or b]


def violations(al: Alignment, w: int) -> set[tuple[int, int]]:
    """Context pairs window ``w`` cannot fire around, from the replay's rules.

    The window fires at the earliest step ``p`` at which its left gates can
    be pulled through the unconsumed context and its right gates through the
    context before the first of them. A context gate must join the window if
    it is unconsumed then and sits before a left gate it does not commute
    with, if it is consumed before then but sits behind such a left gate, or
    if it lies inside the right side's span before a right gate it does not
    commute with."""
    a, b = al.windows[w]
    first = min(b) if b else None
    p = 0
    for i, j in al.match.items():
        c = al.xs[i]
        if first is not None and j >= first:
            continue
        if any(i < x and not can_commute(c, al.xs[x]) for x in a) or \
                any(j < y and not can_commute(c, al.ys[y]) for y in b):
            p = max(p, j + 1)
    out = set()
    for i, j in al.match.items():
        c = al.xs[i]
        if first is not None and j >= first:
            if any(i < x and not can_commute(c, al.xs[x]) for x in a):
                out.add((i, j))
            if any(j < y and not can_commute(c, al.ys[y]) for y in b):
                out.add((i, j))
        elif j < p and any(i > x and not can_commute(c, al.xs[x]) for x in a):
            out.add((i, j))
    return out


def apply_constraints(al: Alignment, w: int) -> bool:
    """Absorb violating context into ``w`` until there is none; True if any."""
    grown = False
    while True:
        pairs = violations(al, w)
        if not pairs:
            return grown
        for i, j in pairs:
            al.absorb(w, i, j)
        grown = True
        if len(al.wires(w)) > SEARCH_MAX_WIRES:
            raise GiveUp(f"a window grew beyond {SEARCH_MAX_WIRES} wires while absorbing the "
                         f"context it must fire around: {al.describe()[w][:200]}")


def fix_invalid(al: Alignment, invalid: list[int]) -> Alignment:
    """Windows that are not equivalences on their own: merge the smallest
    subset of them that becomes one (bounded search), else grow the first by
    the nearest context gate that does not commute with it."""
    from itertools import combinations
    trials = 0
    for size in range(2, min(len(invalid), 4) + 1):
        best = None
        for subset in combinations(invalid, size):
            trials += 1
            if trials > 400:
                break
            trial = al.copy()
            w = trial.merge(list(subset))
            try:
                apply_constraints(trial, w)
            except GiveUp:
                continue
            if window_valid(*trial.lists(w)):
                key = (len(trial.wires(w)), trial.size(w))
                if best is None or key < best[0]:
                    best = (key, subset, trial)
        if best is not None:
            _, subset, trial = best
            trial.log.append("merge non-equivalent windows " +
                             " and ".join(str(w + 1) for w in subset))
            return trial
    al = al.copy()
    w = invalid[0]
    left, right = al.lists(w)
    t = _time(al, w)
    cands = sorted((abs(i - t), i) for i, j in al.match.items()
                   if any(not can_commute(al.xs[i], g) for g in left + right))
    if not cands:
        raise GiveUp(f"{len(invalid)} window(s) are not equivalences on their own, no merge of "
                     f"up to four of them is one within {SEARCH_MAX_WIRES} wires, and window "
                     f"{w + 1} ({len(al.wires(w))} wires, {al.size(w)} gates) has no "
                     "non-commuting context left to grow into")
    _, i = cands[0]
    al.log.append(f"grow non-equivalent window {w + 1} by context gate {show(al.xs[i])}")
    al.absorb(w, i, None)
    return al


def search(xs: list[Gate], ys: list[Gate], canon: str,
           do_rematch: bool = True) -> tuple[Alignment | None, dict]:
    """Refine from the diff until the model replays, or give up. Returns the
    aligned windows (in firing order) or ``None``, and a report."""
    al = initial_alignment(xs, ys, canon)
    report = {"canon": canon, "rematch": do_rematch, "initial": al.stats(), "steps": 0,
              "reason": None, "matched": len(al.match),
              "unmatched": [len(xs) - len(al.match), len(ys) - len(al.match)]}
    if do_rematch:
        al = rematch(al)
    report["rematched"] = al.stats()
    inv = al.inverse()
    ux = [g for i, g in enumerate(xs) if i not in al.match]
    uy = [g for j, g in enumerate(ys) if j not in inv]
    report["unmatched_phases"] = [sum(g[0] in DIAG for g in ux), sum(g[0] in DIAG for g in uy)]
    report["unmatched_other"] = [len(ux) - report["unmatched_phases"][0],
                                 len(uy) - report["unmatched_phases"][1]]
    try:
        for step in range(SEARCH_MAX_STEPS):
            report["steps"] = step
            report["last"] = al.stats()
            state = (sorted(tuple(a) + (-1,) + tuple(b) for a, b in al.windows),
                     sorted(al.match.items()))
            if step and state == report.get("_state"):
                raise GiveUp("refinement makes no progress: " +
                             (al.log[-1] if al.log else "no refinement applied"))
            report["_state"] = state
            if al.windows and max(len(al.wires(w)) for w in range(len(al.windows))) > SEARCH_MAX_WIRES:
                bad = [w + 1 for w in range(len(al.windows)) if not window_valid(*al.lists(w))]
                raise GiveUp(f"a window grew beyond {SEARCH_MAX_WIRES} wires "
                             f"({report['last']['max_wires']} wires, {report['last']['max_gates']} "
                             f"gates) while {'it is still not an equivalence' if bad else 'chasing the context it must fire around'}")
            grown = False
            for w in range(len(al.windows)):
                trial = al.copy()
                if apply_constraints(trial, w):
                    trial.log.append(f"absorb the context window {w + 1} must fire around")
                    al, grown = trial, True
                    break
            if grown:
                continue
            invalid = [w for w in range(len(al.windows)) if not window_valid(*al.lists(w))]
            if invalid:
                report["invalid"] = [al.describe()[w] for w in invalid]
                al = fix_invalid(al, invalid)
                continue
            r = replay(al)
            if r.ok:
                ordered = al.copy()
                ordered.windows = [al.windows[w] for w in r.fired]
                report["final"] = ordered.stats()
                report["log"] = al.log
                return ordered, report
            report["failure"] = {k: v for k, v in r.failure.items() if k not in ("xs", "ys")}
            al = refine(al, r)
        raise GiveUp(f"no replayable alignment within {SEARCH_MAX_STEPS} refinement steps")
    except GiveUp as e:
        report["reason"] = str(e)
        report["log"] = al.log
        report["last"] = al.stats()
        report["last_windows"] = al.describe()
        report["last_invalid"] = [w + 1 for w in range(len(al.windows))
                                  if not window_valid(*al.lists(w))]
    report.pop("_state", None)
    return None, report


def best_alignment(xs: list[Gate], ys: list[Gate]) -> tuple[Alignment | None, list[dict], str]:
    """Search under every canonicalisation, with and without re-matching, and
    keep the replayable alignment with the narrowest widest window and then
    the smallest estimated decide cost. Returns it (or ``None``), all the
    search reports, and the name of the winning search."""
    found, best, attempts, which = None, None, [], ""
    for canon in CANONS:
        for do_rematch in (True, False):
            al, report = search(xs, ys, canon, do_rematch)
            attempts.append(report)
            if al is not None:
                st = al.stats()
                key = (st["max_wires"], st["cost"], st["windows"])
                if best is None or key < best:
                    found, best = al, key
                    which = canon + ("" if do_rematch else " (no re-match)")
    return found, attempts, which


