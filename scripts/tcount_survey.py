def one(name: str, i: int) -> Gate:
    return (name, (i,))


def cx(c: int, t: int) -> Gate:
    return ("CX", (c, t))


def parse(instructions: list[str]) -> list[Gate]:
    """Parse ``check_pyzx_benchmarks.lean_instructions`` strings."""
    gates = []
    for s in instructions:
        name, *wires = s.split()
        gates.append((name, tuple(int(w) for w in wires)))
    return gates


def show(g: Gate) -> str:
    return " ".join([g[0], *map(str, g[1])])


def to_qasm(gates: list[Gate], n: int, header: list[str]) -> str:
    lines = ["OPENQASM 2.0;", 'include "qelib1.inc";'] + [f"// {h}" for h in header]
    lines.append(f"qreg q[{n}];")
    for name, w in gates:
        lines.append(f"{QASM_NAMES[name]} " + ",".join(f"q[{i}]" for i in w) + ";")
    return "\n".join(lines) + "\n"


def ccx(a: int, b: int, c: int) -> list[Gate]:
    """The seven-``T`` Toffoli of ``benchmarks/tof_3/README.md``."""
    return [one("H", c), cx(b, c), one("Tdg", c), cx(a, c), one("T", c), cx(b, c),
            one("Tdg", c), cx(a, c), one("T", b), one("T", c), one("H", c), cx(a, b),
            one("T", a), one("Tdg", b), cx(a, b)]


def ccz(a: int, b: int, c: int) -> list[Gate]:
    """The seven-``T`` doubly-controlled ``Z``: ``ccx`` without its Hadamards."""
    return [cx(b, c), one("Tdg", c), cx(a, c), one("T", c), cx(b, c), one("Tdg", c), cx(a, c),
            one("T", b), one("T", c), cx(a, b), one("T", a), one("Tdg", b), cx(a, b)]


def mod5_4() -> tuple[int, list[Gate]]:
    """``mod5_4`` as in the PyZX repository (``circuits/Fast/mod5_4_before``,
    Quipper ASCII, the NRSCM benchmark): ``X 4; H 4; CCZ 0 3 4; CCZ 2 3 4;
    H 4; CX 3 4; H 4; CCZ 1 2 4; H 4; CX 2 4; H 4; CCZ 0 1 4; H 4; CX 1 4;
    CX 0 4``, each ``CCZ`` in the seven-``T`` decomposition."""
    gates = [one("X", 4), one("H", 4)] + ccz(0, 3, 4) + ccz(2, 3, 4)
    gates += [one("H", 4), cx(3, 4), one("H", 4)] + ccz(1, 2, 4)
    gates += [one("H", 4), cx(2, 4), one("H", 4)] + ccz(0, 1, 4)
    gates += [one("H", 4), cx(1, 4), cx(0, 4)]
    return 5, gates


def tof(n: int) -> tuple[int, list[Gate]]:
    """``tof_n``: an ``n``-controlled NOT through ``n - 2`` clean ancillas.

    Controls ``0..n-1``, ancillas ``n..2n-3``, target ``2n-2``; the ancilla
    chain is computed, the target Toffoli applied, the chain uncomputed.
    """
    ctrl, anc, tgt = list(range(n)), list(range(n, 2 * n - 2)), 2 * n - 2
    chain = [(ctrl[0], ctrl[1], anc[0])] + [(anc[i - 1], ctrl[i + 1], anc[i])
                                            for i in range(1, n - 2)]
    toffolis = chain + [(anc[n - 3], ctrl[n - 1], tgt)] + chain[::-1]
    return 2 * n - 1, [g for t in toffolis for g in ccx(*t)]


def barenco_tof(n: int) -> tuple[int, list[Gate]]:
    """``barenco_tof_n``: Barenco et al. (1995) Lemma 7.2 with dirty ancillas.

    Same wire layout as ``tof``; ``4 (n - 2)`` Toffolis: a V-shaped chain from
    the target down to the first ancilla and back, then the chain again
    without its outermost Toffoli. Every ancilla is restored whatever its
    initial value.
    """
    ctrl, anc, tgt = list(range(n)), list(range(n, 2 * n - 2)), 2 * n - 2
    chain = [(ctrl[n - 1], anc[n - 3], tgt)]
    chain += [(ctrl[i + 1], anc[i - 1], anc[i]) for i in range(n - 3, 0, -1)]
    chain += [(ctrl[0], ctrl[1], anc[0])]
    toffolis = chain + chain[-2::-1] + chain[1:] + chain[-2:0:-1]
    return 2 * n - 1, [g for t in toffolis for g in ccx(*t)]


def cuccaro(n: int) -> tuple[int, list[Gate]]:
    """Cuccaro–Draper–Kutin–Moulton ripple-carry adder on ``n`` bits.

    Wires: carry-in ``0``, then ``b_i = 1 + 2i``, ``a_i = 2 + 2i``, carry-out
    ``2n + 1``. ``MAJ(c, b, a) = CX a b; CX a c; CCX c b a`` and
    ``UMA(c, b, a) = CCX c b a; CX a c; CX c b`` with the Toffoli of ``ccx``.
    """
    c, z = 0, 2 * n + 1
    b, a = [1 + 2 * i for i in range(n)], [2 + 2 * i for i in range(n)]

    def maj(c, b, a):
        return [cx(a, b), cx(a, c)] + ccx(c, b, a)

    def uma(c, b, a):
        return ccx(c, b, a) + [cx(a, c), cx(c, b)]

    gates = maj(c, b[0], a[0])
    for i in range(1, n):
        gates += maj(a[i - 1], b[i], a[i])
    gates += [cx(a[n - 1], z)]
    for i in range(n - 1, 0, -1):
        gates += uma(a[i - 1], b[i], a[i])
    gates += uma(c, b[0], a[0])
    return 2 * n + 2, gates


def random_circuit(qubits: int, depth: int, seed: int, p_had: float,
                   p_t: float) -> tuple[int, list[Gate]]:
    """``pyzx.generate.CNOT_HAD_PHASE_circuit`` with the global RNG seeded."""
    random.seed(seed)
    c = zx.generate.CNOT_HAD_PHASE_circuit(qubits, depth, p_had, p_t)
    return qubits, parse(cpb.lean_instructions(c))


