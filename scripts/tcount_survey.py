#!/usr/bin/env python3
"""T-count survey: align PyZX-optimised circuits with their originals by windows.

The roadmap's working hypothesis (Rung 3) is that an optimiser's output relates
to its input by local rewrites that can be aligned as windows and checked by
``circuit_windows``. This script is the evidence run. For every circuit under
``benchmarks/survey/<name>/original.qasm`` and both PyZX pipelines of
``check_pyzx_benchmarks.py`` (``teleport`` = ``teleport_reduce`` +
``basic_optimization``; ``full_reduce`` = ``full_reduce`` + extraction +
``basic_optimization``) it

1. generates the optimised circuit and saves it as ``pyzx_<pipeline>.qasm``;
2. canonicalises both gate lists (a stable topological order under a
   commutation relation, so that reorderings of commuting gates disappear),
   diffs them with ``difflib.SequenceMatcher`` and turns the opcodes into
   windows ``(a, b)``;
3. replays the alignment in a Python model of the tactic (same
   ``Instr.CanCommute`` rules, same first-pullable-occurrence pull, windows
   fired as early as possible), refines it on failure (merge windows that are
   not equivalences on their own, absorb the gate that blocks a move) a
   bounded number of times, and orders the windows as they fire;
4. emits a Lean file with ``original``, ``optimized`` and
   ``theorem original_equiv_optimized : original ≡ᵤ optimized := by
   circuit_windows [...]`` and checks it with ``lake env lean`` under a
   timeout. Lean is the judge; the numpy unitaries used along the way are an
   untrusted oracle for diagnosis only.

Requires pyzx==0.9.0 and numpy. Results go to ``benchmarks/survey/results.json``;
``--table`` prints them as the Markdown table of ``benchmarks/survey/README.md``.
The circuits are generated by ``--generate`` (seeds recorded in the QASM
headers); the survey itself always reads the saved files.
"""

