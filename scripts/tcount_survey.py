# Commutation, canonical orders, diff
# --------------------------------------------------------------------------

def can_commute(a: Gate, b: Gate) -> bool:
    """Mirror of ``Instr.CanCommute`` in ``CircuitEq/Rewriting.lean``."""
    if a == b:
        return True
    (g, wa), (h, wb) = a, b

    def one_cnot(g, i, c, t):
        return (i != c and i != t) or (c != t and ((i == c and g in DIAG) or (i == t and g == "X")))

    if g != "CX" and h != "CX":
        return wa[0] != wb[0] or (g in DIAG and h in DIAG)
    if g != "CX":
        return one_cnot(g, wa[0], wb[0], wb[1])
    if h != "CX":
        return one_cnot(h, wb[0], wa[0], wa[1])
    return wa[0] != wb[1] and wb[0] != wa[1]


def strict_commute(a: Gate, b: Gate) -> bool:
    """Disjoint wires (or identical gates) only."""
    return a == b or not set(a[1]) & set(b[1])


def _key(g: Gate):
    return (min(g[1]), g[0], g[1])


def canonical_order(gates: list[Gate], canon: str) -> list[int]:
    """A permutation (canonical position -> raw index) that is a linear
    extension of the dependency DAG under the chosen commutation relation.

    ``greedy`` emits the available gate with the smallest ``(min wire, name)``
    key first (a priority topological sort); ``asap`` sorts by longest-path
    layer, then key. ``raw`` keeps the list as it is.
    """
    if canon == "raw":
        return list(range(len(gates)))
    method, rel = canon.split("/")
    commute = can_commute if rel == "cancommute" else strict_commute
    n = len(gates)
    preds = [[i for i in range(j) if not commute(gates[i], gates[j])] for j in range(n)]
    if method == "asap":
        layer = [0] * n
        for j in range(n):
            layer[j] = max([layer[i] + 1 for i in preds[j]], default=0)
        return sorted(range(n), key=lambda k: (layer[k], _key(gates[k]), k))
    succs = [[] for _ in range(n)]
    indeg = [len(p) for p in preds]
    for j in range(n):
        for i in preds[j]:
            succs[i].append(j)
    heap = [(_key(gates[i]), i) for i in range(n) if indeg[i] == 0]
    heapq.heapify(heap)
    order = []
    while heap:
        _, i = heapq.heappop(heap)
        order.append(i)
        for j in succs[i]:
            indeg[j] -= 1
            if indeg[j] == 0:
                heapq.heappush(heap, (_key(gates[j]), j))
    return order


@dataclass
class Alignment:
    """Windows as index sets into the raw lists, plus the context matching."""
    xs: list[Gate]
    ys: list[Gate]
    windows: list[tuple[list[int], list[int]]]
    match: dict[int, int]  # context: raw xs index -> raw ys index
    canon: str
    log: list[str] = field(default_factory=list)

    def copy(self) -> "Alignment":
        return Alignment(self.xs, self.ys, [(list(a), list(b)) for a, b in self.windows],
                         dict(self.match), self.canon, list(self.log))

    def inverse(self) -> dict[int, int]:
        return {j: i for i, j in self.match.items()}

    def owner_x(self, i: int) -> int | None:
        return next((w for w, (a, _) in enumerate(self.windows) if i in a), None)

    def owner_y(self, j: int) -> int | None:
        return next((w for w, (_, b) in enumerate(self.windows) if j in b), None)

    def lists(self, w: int) -> tuple[list[Gate], list[Gate]]:
        a, b = self.windows[w]
        return [self.xs[i] for i in a], [self.ys[j] for j in b]

    def wires(self, w: int) -> list[int]:
        return window_wires(*self.lists(w))

    def size(self, w: int) -> int:
        a, b = self.windows[w]
        return len(a) + len(b)

    def absorb(self, w: int, i: int | None, j: int | None) -> None:
        """Move a context pair (or one side of it) into window ``w``."""
        a, b = self.windows[w]
        if i is not None:
            if i in self.match:
                jj = self.match.pop(i)
                if j is None:
                    j = jj
            if i not in a:
                a.append(i)
                a.sort()
        if j is not None and j not in b:
            b.append(j)
            b.sort()

    def merge(self, ws: list[int]) -> int:
        ws = sorted(set(ws))
        a = sorted({i for w in ws for i in self.windows[w][0]})
        b = sorted({j for w in ws for j in self.windows[w][1]})
        for w in reversed(ws):
            del self.windows[w]
        self.windows.append((a, b))
        return len(self.windows) - 1

    def new_window(self, i: int, j: int) -> int:
        assert self.match.get(i) == j
        del self.match[i]
        self.windows.append(([i], [j]))
        return len(self.windows) - 1

    def cost(self) -> int:
        """Estimated decide cost, gates times ``4^k`` summed over the windows."""
        return sum(self.size(w) * 4 ** len(self.wires(w)) for w in range(len(self.windows)))

    def stats(self) -> dict:
        if not self.windows:
            return {"windows": 0, "max_wires": 0, "max_gates": 0, "cost": 0}
        return {"windows": len(self.windows),
                "max_wires": max(len(self.wires(w)) for w in range(len(self.windows))),
                "max_gates": max(self.size(w) for w in range(len(self.windows))),
                "cost": self.cost()}

    def describe(self) -> list[str]:
        return [f"[{', '.join(map(show, l))}] <-> [{', '.join(map(show, r))}]"
                for l, r in (self.lists(w) for w in range(len(self.windows)))]


def initial_alignment(xs: list[Gate], ys: list[Gate], canon: str) -> Alignment:
    """Diff the canonical orders; opcodes become windows, equal runs context."""
    px, py = canonical_order(xs, canon), canonical_order(ys, canon)
    cx_, cy_ = [xs[i] for i in px], [ys[j] for j in py]
    sm = difflib.SequenceMatcher(None, cx_, cy_, autojunk=False)
    windows, match = [], {}
    for tag, i1, i2, j1, j2 in sm.get_opcodes():
        if tag == "equal":
            for k in range(i2 - i1):
                match[px[i1 + k]] = py[j1 + k]
        else:
            windows.append((sorted(px[i1:i2]), sorted(py[j1:j2])))
    return Alignment(xs, ys, windows, match, canon)


