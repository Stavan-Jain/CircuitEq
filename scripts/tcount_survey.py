def lean_list(gates: list[Gate], indent: int, width: int = 80) -> str:
    """Format ``[g₁, g₂, …]`` wrapped at ``width`` columns."""
    items = [show(g) for g in gates]
    if not items:
        return "[]"
    lines, cur = [], "[" + items[0]
    for it in items[1:]:
        if len(cur) + 2 + len(it) + 1 > width - indent:
            lines.append(cur + ",")
            cur = it
        else:
            cur += ", " + it
    lines.append(cur + "]")
    return ("\n" + " " * indent).join(lines)


def lean_windows(al: Alignment) -> str:
    parts = []
    for w in range(len(al.windows)):
        l, r = al.lists(w)
        parts.append(f"({lean_list(l, 8)},\n        {lean_list(r, 8)})")
    return "[" + ",\n      ".join(parts) + "]"


def lean_module(namespace: str, n: int, xs: list[Gate], ys: list[Gate], al: Alignment,
                header: str = "") -> str:
    return (f"{header}import CircuitEq.Tactic\n\nnamespace {namespace}\n\nopen Instr\n\n"
            f"def original : Circuit {n} :=\n  {lean_list(xs, 4)}\n\n"
            f"def optimized : Circuit {n} :=\n  {lean_list(ys, 4)}\n\n"
            f"theorem original_equiv_optimized : original ≡ᵤ optimized := by\n"
            f"  circuit_windows\n    {lean_windows(al)}\n\nend {namespace}\n")


def run_lean(path: Path, timeout: float) -> dict:
    """``lake env lean path`` with a hard timeout (the process group is killed)."""
    t0 = time.time()
    p = subprocess.Popen(["lake", "env", "lean", str(path)], cwd=ROOT, stdout=subprocess.PIPE,
                         stderr=subprocess.STDOUT, text=True, start_new_session=True)
    try:
        out, _ = p.communicate(timeout=timeout)
        timed_out = False
    except subprocess.TimeoutExpired:
        os.killpg(p.pid, signal.SIGKILL)
        out, _ = p.communicate()
        timed_out = True
    elapsed = time.time() - t0
    errors = re.findall(r"^.*?:\d+:\d+: error: (.*)$", out, re.M)
    return {"ok": p.returncode == 0 and not timed_out and not errors, "time": round(elapsed, 1),
            "timeout": timed_out, "errors": errors, "output": out[-4000:]}


def classify_lean_error(msg: str) -> str:
    if "is blocked by a gate" in msg:
        return "blocked move"
    if "does not occur" in msg:
        return "absent gate"
    if "could not be placed" in msg:
        return "window not placed"
    if "unmatched instructions" in msg:
        return "unmatched left"
    if "not an equivalence" in msg:
        return "window refuted"
    return "other"


