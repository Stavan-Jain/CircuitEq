def generate(force: bool = False) -> None:
    """Write ``benchmarks/survey/<name>/original.qasm`` for every circuit."""
    for name, (header, n, gates) in circuit_table().items():
        d = SURVEY / name
        d.mkdir(parents=True, exist_ok=True)
        path = d / "original.qasm"
        if name == "tof_3":
            src = ROOT / "benchmarks" / "tof_3" / "original.qasm"
            if parse(cpb.lean_instructions(zx.Circuit.load(str(src)))) != gates:
                raise RuntimeError("tof(3) does not reproduce benchmarks/tof_3/original.qasm")
            if force or not path.exists():
                shutil.copy(src, path)
            continue
        text = to_qasm(gates, n, header)
        if path.exists() and not force:
            if path.read_text() != text:
                print(f"{name}: existing original.qasm differs from the generator; "
                      "use --force to overwrite", file=sys.stderr)
            continue
        path.write_text(text)
        loaded = zx.Circuit.load(str(path))
        if loaded.qubits != n or parse(cpb.lean_instructions(loaded)) != gates:
            raise RuntimeError(f"{name}: QASM round trip changed the circuit")
        print(f"{name}: {n} qubits, {len(gates)} gates, T-count {loaded.tcount()}")


